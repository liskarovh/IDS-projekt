-- Procedura VLOZ_NOVOU_PLATBU:
-- Přidá novou platbu od zákazníka na základě jeho jména a IČO doručovatele.
-- Pokud zákazník nebo doručovatel neexistují, vyvolá výjimku.
-- Používá datové typy %TYPE, kontrolu existence, a EXCEPTION blok.

CREATE OR REPLACE PROCEDURE vloz_novou_platbu (
  jmeno_zakaznika IN Zakaznik.jmeno_prijmeni%TYPE,
  ico_dorucovatele IN Dorucovatel.ico%TYPE,
  variabilni_symbol IN Platba.variabilnysymbol%TYPE,
  castka IN Platba.suma%TYPE
)
IS
  zakaznik_ucet Uzivatel.cislo_uctu%TYPE;
  dorucovatel_ucet Uzivatel.cislo_uctu%TYPE;
BEGIN
  -- Získání cisla_uctu zákazníka podle jména
  SELECT z.cislo_uctu
  INTO zakaznik_ucet
  FROM Zakaznik z
  WHERE z.jmeno_prijmeni = jmeno_zakaznika;

  -- Získání cisla_uctu doručovatele podle IČO
  SELECT d.cislo_uctu
  INTO dorucovatel_ucet
  FROM Dorucovatel d
  WHERE d.ico = ico_dorucovatele;

  -- Vložení nové platby
  INSERT INTO Platba (variabilnysymbol, datum, suma, cislo_odesilatele, cislo_prijimatele)
  VALUES (variabilni_symbol, SYSDATE, castka, zakaznik_ucet, dorucovatel_ucet);

  DBMS_OUTPUT.PUT_LINE('Platba vložena úspěšně.');

EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('Zákazník nebo doručovatel nebyl nalezen.');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Chyba při vkládání platby: ' || SQLERRM);
END;
/


