-- Procedura VYPIS_PLATBY_ZAKAZNIKU:
-- Vypíše všechny platby od zákazníka podle jména.
-- Používá kurzor, %ROWTYPE, výpis pomocí DBMS_OUTPUT a ošetření výjimek.

CREATE OR REPLACE PROCEDURE vypis_platby_zakazniku (
  jmeno_zakaznika IN Zakaznik.jmeno_prijmeni%TYPE
)
IS
  zakaznik_cislo Uzivatel.cislo_uctu%TYPE;

  CURSOR platby_cur IS
    SELECT p.*, d.nazev_spolecnosti
    FROM Platba p
    JOIN Dorucovatel d ON p.cislo_prijimatele = d.cislo_uctu
    WHERE p.cislo_odesilatele = zakaznik_cislo;

  platba_rec platby_cur%ROWTYPE;
BEGIN
  -- Získání cisla_uctu podle jména zákazníka
  SELECT z.cislo_uctu
  INTO zakaznik_cislo
  FROM Zakaznik z
  WHERE z.jmeno_prijmeni = jmeno_zakaznika;

  -- Otevření kurzoru
  OPEN platby_cur;
  LOOP
    FETCH platby_cur INTO platba_rec;
    EXIT WHEN platby_cur%NOTFOUND;

    -- Výpis jedné platby
    DBMS_OUTPUT.PUT_LINE(
      'Datum: ' || TO_CHAR(platba_rec.datum, 'DD.MM.YYYY') ||
      ', Částka: ' || platba_rec.suma ||
      ', VS: ' || platba_rec.variabilnysymbol ||
      ', Příjemce: ' || platba_rec.nazev_spolecnosti ||
      ' (Účet: ' || platba_rec.cislo_prijimatele || ')'
    );
  END LOOP;
  CLOSE platby_cur;

EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('Zákazník nebyl nalezen.');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Chyba při výpisu plateb: ' || SQLERRM);
END;
/

BEGIN
  vypis_platby_zakazniku('Petr Zakaznik');
END;
