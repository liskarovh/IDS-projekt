-- Tento dotaz zobrazuje všechny zákazníky spolu s jejich adresou, stavem předplatného a seznamem odebíraných tiskovin.
-- Stav předplatného je určen pomocí CASE:
--  - 'Pozastaveno', pokud má zákazník právě aktivní záznam o dočasném přerušení odběru
--  - 'Aktivní', pokud má přiřazenou alespoň jednu tiskovinu
--  - 'Bez předplatného', pokud žádné předplatné nemá
-- Pomocí LISTAGG jsou názvy tiskovin spojeny do jednoho sloupce.

WITH zakaznici_s_predplatnym AS (
  SELECT DISTINCT zt.zakaznik_cislo_uctu, zt.zakaznik_id
  FROM Zakaznik_Tiskovina zt
),
tiskoviny_uzivatele AS (
  SELECT
    zt.zakaznik_cislo_uctu,
    zt.zakaznik_id,
    LISTAGG(t.nazev, ', ') WITHIN GROUP (ORDER BY t.nazev) AS tiskoviny
  FROM Zakaznik_Tiskovina zt
  JOIN Tiskovina t ON zt.kod_tiskoviny = t.kod_tiskoviny
  GROUP BY zt.zakaznik_cislo_uctu, zt.zakaznik_id
)
SELECT 
  z.jmeno_prijmeni,
  z.adresa,
  CASE
    WHEN EXISTS (
      SELECT 1
      FROM Doba_Neodoberania d
      WHERE d.cislo_uctu = z.cislo_uctu
        AND d.zakaznik_id = z.id
        AND SYSDATE BETWEEN d.zacatek AND NVL(d.konec, SYSDATE)
    ) THEN 'Pozastaveno'
    WHEN zp.zakaznik_cislo_uctu IS NOT NULL THEN 'Aktivní'
    ELSE 'Bez předplatného'
  END AS stav_predplatne,
  NVL(tu.tiskoviny, '–') AS odebira
FROM Zakaznik z
LEFT JOIN zakaznici_s_predplatnym zp
  ON z.cislo_uctu = zp.zakaznik_cislo_uctu AND z.id = zp.zakaznik_id
LEFT JOIN tiskoviny_uzivatele tu
  ON z.cislo_uctu = tu.zakaznik_cislo_uctu AND z.id = tu.zakaznik_id
ORDER BY z.jmeno_prijmeni;