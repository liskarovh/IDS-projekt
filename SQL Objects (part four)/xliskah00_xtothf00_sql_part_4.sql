-- Trigger `audit_mazani_plateb` slouží k auditu každé operace DELETE
-- na tabulce `Platba`. Reaguje na příkaz DELETE tím, že:
-- 
-- 1. Pomocí Oracle funkce `USER` zjistí, kdo je aktuálně přihlášený
--    databázový uživatel (např. 'XLISKAH00').
--
-- 2. Pomocí mapovací tabulky `Uzivatele_Mapping` zjistí, který z
--    aplikačních uživatelů (tabulka `Uzivatel`) odpovídá tomuto
--    databázovému účtu – tedy získá `cislo_uctu`.
--
-- 3. Z tabulky `Uzivatel` následně získá informaci, zda má uživatel
--    administrátorská práva (`admin_prava`).
--
-- 4. Spočítá, kolik záznamů po provedeném DELETE v tabulce `Platba`
--    zůstává (nejde zjistit kolik jich bylo smazáno, protože Oracle
--    to v příkazovém triggeru neumožňuje přímo).
--
-- 5. Vloží do auditní tabulky `Audit_Delete` informaci o:
--    - čísle účtu uživatele (`cislo_uctu`)
--    - počtu záznamů, které v `Platba` zůstaly
--    - textovém komentáři podle typu oprávnění
--    - čase operace (defaultně přes TIMESTAMP sloupec `kdy`)

CREATE OR REPLACE TRIGGER audit_mazani_plateb
AFTER DELETE ON Platba
DECLARE
  id_uzivatele Uzivatel.cislo_uctu%TYPE;
  je_admin     Uzivatel.admin_prava%TYPE;
  pocet        NUMBER;
  komentar     VARCHAR2(255);
BEGIN
  -- Zjisti přihlášeného uživatele z mapovací tabulky
  BEGIN
    SELECT u.cislo_uctu, u.admin_prava
    INTO id_uzivatele, je_admin
    FROM Uzivatel u
    JOIN Uzivatele_Mapping m ON u.cislo_uctu = m.cislo_uctu
    WHERE UPPER(m.db_user) = UPPER(USER);
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      id_uzivatele := NULL;
      je_admin := NULL;
      komentar := 'Mazání provedeno neznámým nebo nezmapovaným uživatelem.';
  END;

  -- Vytvoř komentář na základě oprávnění
  IF je_admin = 1 THEN
    komentar := 'Mazání provedeno administrátorem.';
  ELSIF je_admin = 0 THEN
    komentar := 'Mazání provedeno běžným uživatelem.';
  END IF;

  -- Spočítej zbylé záznamy v tabulce Platba
  SELECT COUNT(*) INTO pocet FROM Platba;

  -- Zaloguj do auditní tabulky
  INSERT INTO Audit_Delete (uzivatel, pocet_zbyvajicich, komentar)
  VALUES (id_uzivatele, pocet, komentar);
END;
/

DELETE FROM Zakaznik_Tiskovina
WHERE platba = (SELECT id FROM Platba WHERE ROWNUM = 1);

DELETE FROM Platba WHERE ROWNUM = 1;
COMMIT;

SELECT 
  a.audit_id,
  a.kdy,
  a.uzivatel AS cislo_uctu,
  u.admin_prava,
  u.cislo_uctu,
  s.jmeno_prijmeni,
  a.pocet_zbyvajicich,
  a.komentar
FROM Audit_Delete a
LEFT JOIN Uzivatel u ON a.uzivatel = u.cislo_uctu
LEFT JOIN (
    SELECT cislo_uctu, jmeno_prijmeni FROM Spravce
    UNION ALL
    SELECT cislo_uctu, jmeno_prijmeni FROM Zakaznik
) s ON a.uzivatel = s.cislo_uctu
ORDER BY a.audit_id DESC;



-- Trigger UPDATE_ICO_DORUCOVATELE zajišťuje, že pokud dojde ke změně IČO v tabulce DORUCOVATEL,
-- automaticky se tato nová hodnota promítne i do všech závislých tabulek: TISKOVINA a SEZNAM.
-- Konkrétně aktualizuje:
--   - sloupec TISKOVINA.dorucovatel_ico
--   - sloupec SEZNAM.ico_dorucovatele
-- Spouští se po změně sloupce "ico" v tabulce DORUCOVATEL (AFTER UPDATE OF ico).
-- 
-- Aby mohl tento trigger fungovat:
--   - je nutné dočasně odstranit cizí klíče z tabulek TISKOVINA a SEZNAM, které brání změně hodnoty v DORUCOVATEL
--   - po provedení změny lze tyto cizí klíče znovu přidat
-- 
-- Trigger tímto způsobem simuluje chování ON UPDATE CASCADE, které Oracle běžně nepodporuje.


CREATE OR REPLACE TRIGGER update_ico_dorucovatele
AFTER UPDATE OF ico ON Dorucovatel
FOR EACH ROW
BEGIN
  -- Aktualizace IČO v tabulce TISKOVINA
  UPDATE Tiskovina
  SET dorucovatel_ico = :NEW.ico
  WHERE dorucovatel_cislo_uctu = :OLD.cislo_uctu
    AND dorucovatel_ico = :OLD.ico;

  -- Aktualizace IČO v tabulce SEZNAM
  UPDATE Seznam
  SET ico_dorucovatele = :NEW.ico
  WHERE cislo_uctu = :OLD.cislo_uctu
    AND ico_dorucovatele = :OLD.ico;
END;
/


-- Odstranění cizího klíče z Tiskovina a Seznam na Dorucovatel
BEGIN
  FOR c IN (
    SELECT constraint_name, table_name
    FROM user_constraints
    WHERE constraint_type = 'R'
      AND r_owner = USER
      AND r_constraint_name IN (
        SELECT constraint_name
        FROM user_constraints
        WHERE table_name = 'DORUCOVATEL'
          AND constraint_type = 'P'
      )
      AND table_name IN ('SEZNAM', 'TISKOVINA')
  ) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || c.table_name || ' DROP CONSTRAINT ' || c.constraint_name;
  END LOOP;
END;
